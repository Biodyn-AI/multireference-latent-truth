"""Tests of the fresh release-copy check ``src/r2/release_check.py`` (file list, environment, table
comparison).  Nothing here copies the repository or runs a stage."""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from r2 import release_check as RC  # noqa: E402


def _tables(root: Path, files: dict[str, str]) -> Path:
    d = root / "data" / "r2" / "tables"
    d.mkdir(parents=True)
    for n, txt in files.items():
        (d / f"{n}.csv").write_text(txt)
    return d


def test_compare_tables_classifies_differences(tmp_path):
    ref = _tables(tmp_path / "ref", {
        "same": "a,b\n1,2\n", "rep_bayes": "x,runtime_s\n1,3.2\n", "fit_x": "x,y\n1,2\n",
        "pipeline_stage_timings": "stage,wall_time_s\np,1\n", "gone": "a\n1\n", "paths": "p\n/old/root/x\n"})
    dest = tmp_path / "copy"
    _tables(dest, {
        "same": "a,b\n1,2\n", "rep_bayes": "x,runtime_s\n1,4.0\n", "fit_x": "x,y\n1,3\n",
        "pipeline_stage_timings": "stage,wall_time_s\np,2\n", "new": "a\n1\n", "paths": f"p\n{dest}/x\n"})
    st = {r["table"]: r for r in RC.compare_tables(dest, ref)}
    assert st["same"]["status"] == "identical"
    assert st["rep_bayes"]["status"] == "timing_columns_only" and st["rep_bayes"]["differing_columns"] == "runtime_s"
    assert st["fit_x"]["status"] == "differs" and st["fit_x"]["differing_columns"] == "y"
    assert st["pipeline_stage_timings"]["status"] == "run_table"
    assert st["gone"]["status"] == "missing_in_copy" and st["new"]["status"] == "only_in_copy"
    assert st["paths"]["status"] == "differs" and "path assumption" in st["paths"]["note"]


def test_timing_column_pattern():
    for c in ("runtime_s", "wall_time_s", "total_runtime_s", "started_at", "checked_at", "written"):
        assert RC.TIMING_COL.search(c), c
    for c in ("compress_s", "n_runs", "lift_tf_matched", "auroc", "spearman_observed", "t_nuts_projected"):
        assert not RC.TIMING_COL.search(c), c


def test_clean_env_hides_the_external_data(monkeypatch, tmp_path):
    monkeypatch.setenv("BIODYN_EXT", "/Volumes/Crucial X6/MacBook/biomechinterp/biodyn-work")
    monkeypatch.setenv("SOME_DATA_ROOT", "/Volumes/Crucial X6/other")
