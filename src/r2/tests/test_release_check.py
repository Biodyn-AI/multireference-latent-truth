def test_reads_outside_the_copy(tmp_path):
    dest = tmp_path / "copy"
    tr = dest / "outputs" / "r2" / "pipeline" / "logs" / "r1" / "trace"
    tr.mkdir(parents=True)
    other = tmp_path / "original" / "outputs" / "r2" / "x.json"
    other.parent.mkdir(parents=True)
    other.write_text("{}")
    env = tmp_path / "lib" / "site-packages" / "m.py"
    env.parent.mkdir(parents=True)
    env.write_text("")
    inside = dest / "outputs" / "r2" / "y.json"
    inside.write_text("{}")
    (tr / "s__t.txt").write_text(f"R\t1\t{other}\nR\t1\t{env}\nR\t1\t{inside}\n")
    out = RC.reads_outside(dest)
    assert out["data"] == [f"s__t: {other}"] and len(out["environment"]) == 1


def test_compare_asset_classifies_provenance_and_timing(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    for d in (a, b):
        (d / "tables").mkdir(parents=True)
    pairs = {
        "tables/tab_x.tex": ("% provenance: x generated by src/r2/paper_assets on 2026-10-14 20:39 from t\n"
                             "%   s.csv (modified 2026-10-14 19:28): all rows\nA & 1.0 \\\\\n",
                             "% provenance: x generated by src/r2/paper_assets on 2026-10-14 23:14 from t\n"
                             "%   s.csv (modified 2026-10-14 21:57): all rows\nA & 1.0 \\\\\n"),
        "tables/tab_y.tex": ("A & 1.0 \\\\\n", "A & 1.1 \\\\\n"),
        "tables/tab_compute.tex": ("Stage & 0.66 \\\\\n", "Stage & 0.72 \\\\\n"),
        "numbers.tex": ("\\newcommand{\\nPipeTablesMin}{72}\n\\newcommand{\\nFoo}{1}\n",
                        "\\newcommand{\\nPipeTablesMin}{73}\n\\newcommand{\\nFoo}{1}\n"),
        "numbers_bad.tex": ("\\newcommand{\\nPipeTablesMin}{72}\n\\newcommand{\\nFoo}{1}\n",
                            "\\newcommand{\\nPipeTablesMin}{72}\n\\newcommand{\\nFoo}{2}\n"),
        "digest.md": ("Generated 2026-10-14 20:39 by x\n| `a.csv` | 2026-10-14 20:38 | no | no |\n"
                      "Reports of the modules regenerating tables: `x_REPORT.txt`: 2026-10-14 12:10\n",
                      "Generated 2026-10-14 23:14 by x\n| `a.csv` | 2026-10-14 23:10 | no | no |\n"
                      "Reports of the modules regenerating tables: `x_REPORT.txt`: absent\n"),
    }
    for rel, (x, y) in pairs.items():
        (a / rel).write_text(x)
        (b / rel).write_text(y)
    st = {rel: RC.compare_asset(rel, a / rel, b / rel, tmp_path / "r")[0] for rel in pairs}
    assert st == {"tables/tab_x.tex": "provenance_only", "tables/tab_y.tex": "differs",
                  "tables/tab_compute.tex": "timing_only", "numbers.tex": "timing_only",
                  "numbers_bad.tex": "differs", "digest.md": "provenance_only"}
    assert RC.compare_asset("tables/z.tex", a / "numbers.tex", b / "missing.tex", tmp_path)[0] == "missing_in_copy"


def test_release_table_rows_count_the_regenerated_tables(tmp_path):
    arch = tmp_path / "a.tar.gz"
    arch.write_bytes(b"x" * 2048)
    comp = [dict(table="t1", status="identical"), dict(table="t2", status="timing_columns_only"),
            dict(table="scale_environment", status="run_table"), dict(table="rep_power", status="identical"),
            dict(table="pipeline_stage_timings", status="run_table")]
    summary = dict(n_verified=7, n_repo_files=9, copy_run_exit=0, kept_tables=["rep_power", "pipeline_stage_timings"],
                   reads_outside_copy_data=[], finished="2026-10-14T23:09:21")
    assets = dict(copy_run_exit=0, n_assets=4, counts={"provenance_only": 2, "rendered_identical": 1,
                                                       "timing_only": 1}, differs=[], finished="x")
    rows = {(r["check"], r["key"]): r["value"] for r in RC.release_table_rows(summary, comp, assets, arch)}
    assert rows[("archive", "bytes_compressed")] == 2048 and rows[("archive", "n_files")] == 7
    assert rows[("tables", "n_tables")] == 5 and rows[("tables", "n_regenerated")] == 3
    assert rows[("tables", "n_regenerated_identical")] == 1
    assert rows[("tables", "n_regenerated_timing_only")] == 1 and rows[("tables", "n_regenerated_run_records")] == 1
    assert rows[("tables", "n_kept")] == 2 and rows[("tables", "n_differ")] == 0
    assert rows[("paper_assets", "n_same")] == 3 and rows[("paper_assets", "n_timing_only")] == 1
    assert rows[("paper_assets", "n_differ")] == 0
