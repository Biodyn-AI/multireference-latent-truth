#!/usr/bin/env python3
"""Fit an EM latent-truth model on coverage-aware binary edge annotations.

Model:
- latent edge truth z_i in {0,1}
- source-specific sensitivity alpha_j = P(y_ij=1 | z_i=1)
- source-specific false-positive rate beta_j = P(y_ij=1 | z_i=0)
- edge posterior gamma_i = P(z_i=1 | observations)

Missing values are allowed and handled explicitly.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

import numpy as np
import pandas as pd

from ltm_utils import parse_kind_list


_EPS = 1e-9


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--matrix",
        type=Path,
        default=Path("subproject_24_multireference_latent_truth_model/implementation/outputs/evidence_matrix_wide.csv"),
        help="Coverage-aware binary evidence matrix.",
    )
    parser.add_argument(
        "--source-meta",
        type=Path,
        default=Path("subproject_24_multireference_latent_truth_model/implementation/outputs/source_metadata.csv"),
        help="Source metadata generated by build_evidence_matrix.py.",
    )
    parser.add_argument(
        "--include-kinds",
        type=str,
        default="reference,mechanistic",
        help="Comma-separated source kinds used as annotators.",
    )
    parser.add_argument(
        "--exclude-sources",
        type=str,
        default="",
        help="Comma-separated source IDs to exclude.",
    )
    parser.add_argument(
        "--max-edges",
        type=int,
        default=0,
        help="Optional max rows for debugging (0 means full matrix).",
    )
    parser.add_argument("--max-iter", type=int, default=200)
    parser.add_argument("--tol", type=float, default=1e-6)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("subproject_24_multireference_latent_truth_model/implementation/outputs"),
    )
    return parser.parse_args()


def _select_annotators(
    source_meta: pd.DataFrame,
    include_kinds: List[str],
    exclude_sources: List[str],
) -> List[str]:
    sel = source_meta[source_meta["kind"].isin(include_kinds)].copy()
    if exclude_sources:
        sel = sel[~sel["source_id"].isin(exclude_sources)]
    sel = sel.sort_values("source_id").reset_index(drop=True)
    return sel["source_id"].tolist()


def _em_fit(y: np.ndarray, max_iter: int, tol: float):
    """Run EM with missing labels encoded as NaN in y."""

    obs = ~np.isnan(y)
    y0 = np.nan_to_num(y, nan=0.0)

    n_edges, n_ann = y.shape

    # Initialize gamma from observed positive rates where available.
    edge_pos_rate = np.where(obs.any(axis=1), np.nanmean(y, axis=1), np.nan)
    global_pos = np.nanmean(edge_pos_rate)
    if np.isnan(global_pos):
        global_pos = 0.1
    gamma = np.where(np.isnan(edge_pos_rate), global_pos, edge_pos_rate)
    gamma = np.clip(gamma, 0.01, 0.99)

    alpha = np.full(n_ann, 0.80, dtype=float)
    beta = np.full(n_ann, 0.10, dtype=float)
    pi = float(np.clip(np.mean(gamma), 0.01, 0.99))

    trace = []

    for it in range(1, max_iter + 1):
        # E-step: compute posterior gamma_i per edge.
        log_p1 = np.full(n_edges, np.log(pi + _EPS), dtype=float)
        log_p0 = np.full(n_edges, np.log(1.0 - pi + _EPS), dtype=float)

        for j in range(n_ann):
            mask = obs[:, j]
            yj = y0[:, j]

            if np.any(mask):
                log_p1[mask] += yj[mask] * np.log(alpha[j] + _EPS) + (1.0 - yj[mask]) * np.log(
                    1.0 - alpha[j] + _EPS
                )
                log_p0[mask] += yj[mask] * np.log(beta[j] + _EPS) + (1.0 - yj[mask]) * np.log(
                    1.0 - beta[j] + _EPS
                )

        max_log = np.maximum(log_p1, log_p0)
        log_denom = max_log + np.log(np.exp(log_p1 - max_log) + np.exp(log_p0 - max_log))
        gamma = np.exp(log_p1 - log_denom)
        gamma = np.clip(gamma, _EPS, 1.0 - _EPS)

        # M-step: update prior and source reliabilities with simple pseudocount smoothing.
        pi = float(np.clip(np.mean(gamma), 0.001, 0.999))

        for j in range(n_ann):
            mask = obs[:, j]
            if not np.any(mask):
                alpha[j] = 0.5
                beta[j] = 0.5
                continue

            yj = y0[mask, j]
            gj = gamma[mask]

            # Beta(1,1)-style smoothing by adding one pseudo observation per class outcome.
            alpha_num = float(np.sum(gj * yj) + 1.0)
            alpha_den = float(np.sum(gj) + 2.0)
            beta_num = float(np.sum((1.0 - gj) * yj) + 1.0)
            beta_den = float(np.sum(1.0 - gj) + 2.0)

            alpha[j] = np.clip(alpha_num / max(alpha_den, _EPS), 0.001, 0.999)
            beta[j] = np.clip(beta_num / max(beta_den, _EPS), 0.001, 0.999)

        ll = float(np.sum(log_denom))
        trace.append({"iter": it, "log_likelihood": ll, "pi": pi})

        if it > 1:
            if abs(trace[-1]["log_likelihood"] - trace[-2]["log_likelihood"]) < tol:
                break

    return gamma, alpha, beta, pi, pd.DataFrame(trace)


def main() -> None:
    args = _parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    matrix = pd.read_csv(args.matrix)
    source_meta = pd.read_csv(args.source_meta)

    include_kinds = parse_kind_list(args.include_kinds)
    exclude_sources = parse_kind_list(args.exclude_sources)
    annotators = _select_annotators(source_meta, include_kinds, exclude_sources)
    if not annotators:
        raise ValueError("No annotators selected. Check --include-kinds/--exclude-sources.")

    keep_cols = ["source", "target"] + annotators
    mat = matrix[keep_cols].copy()

    if args.max_edges > 0:
        mat = mat.head(args.max_edges).copy()

    y = mat[annotators].to_numpy(dtype=float)
    gamma, alpha, beta, pi, trace = _em_fit(y=y, max_iter=args.max_iter, tol=args.tol)

    posterior = mat[["source", "target"]].copy()
    posterior["posterior"] = gamma
    posterior["posterior_logit"] = np.log(np.clip(gamma, _EPS, 1.0 - _EPS)) - np.log(
        np.clip(1.0 - gamma, _EPS, 1.0 - _EPS)
    )

    obs = ~np.isnan(y)
    y0 = np.nan_to_num(y, nan=0.0)
    posterior["n_observed_sources"] = obs.sum(axis=1)
    posterior["n_positive_sources"] = (y0 * obs).sum(axis=1)

    reliability = pd.DataFrame(
        {
            "source_id": annotators,
            "alpha_sensitivity": alpha,
            "beta_false_positive": beta,
            "youden_j": alpha - beta,
            "observed_edges": obs.sum(axis=0),
        }
    )
    reliability = reliability.merge(source_meta[["source_id", "kind"]], on="source_id", how="left")
    reliability = reliability.sort_values("youden_j", ascending=False).reset_index(drop=True)

    fit_summary = pd.DataFrame(
        [
            {
                "n_edges": len(mat),
                "n_annotators": len(annotators),
                "pi_prevalence": pi,
                "iterations": int(trace["iter"].max()),
                "final_log_likelihood": float(trace["log_likelihood"].iloc[-1]),
                "include_kinds": ",".join(include_kinds),
                "exclude_sources": ",".join(exclude_sources),
            }
        ]
    )

    posterior.to_csv(args.output_dir / "ltm_em_edge_posteriors.csv", index=False)
    reliability.to_csv(args.output_dir / "ltm_em_source_reliability.csv", index=False)
    trace.to_csv(args.output_dir / "ltm_em_fit_trace.csv", index=False)
    fit_summary.to_csv(args.output_dir / "ltm_em_fit_summary.csv", index=False)

    print("EM latent-truth fit complete:")
    print(f"- edges: {len(mat)}")
    print(f"- annotators: {len(annotators)}")
    print(f"- prevalence pi: {pi:.6f}")
    print(f"- iterations: {int(trace['iter'].max())}")
    print(f"- outputs: {args.output_dir}")


if __name__ == "__main__":
    main()
